CREATE TABLE stray_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    species TEXT NOT NULL CHECK (species IN ('Dog', 'Cat')),
    urgency TEXT NOT NULL CHECK (urgency IN ('Normal', 'Injured', 'Aggressive', 'Abandoned')),
    purok TEXT NOT NULL,
    street_landmark TEXT NOT NULL,
    map_x NUMERIC(5,2) DEFAULT 50.00,
    map_y NUMERIC(5,2) DEFAULT 50.00,
    description TEXT NOT NULL,
    reporter_name TEXT NOT NULL,
    reporter_contact TEXT NOT NULL,
    photo_url TEXT,
    status TEXT NOT NULL DEFAULT 'Reported' CHECK (status IN ('Reported', 'Dispatched', 'Rescued', 'In Barangay Holding/Shelter')),
    intake_notes TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE animals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    species TEXT NOT NULL CHECK (species IN ('Dog', 'Cat')),
    breed TEXT DEFAULT 'Aspin',
    estimated_age TEXT NOT NULL,
    gender TEXT NOT NULL CHECK (gender IN ('Male', 'Female')),
    temperament TEXT NOT NULL,
    anti_rabies BOOLEAN DEFAULT FALSE,
    spayed_neutered BOOLEAN DEFAULT FALSE,
    health_notes TEXT DEFAULT 'Healthy and cleared for adoption.',
    adoption_status TEXT NOT NULL DEFAULT 'Available' CHECK (adoption_status IN ('Available', 'Pending', 'Adopted')),
    photo_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE adoption_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id BIGINT REFERENCES animals(id) ON DELETE CASCADE,
    animal_name TEXT NOT NULL,
    applicant_name TEXT NOT NULL,
    applicant_contact TEXT NOT NULL,
    purok_address TEXT NOT NULL,
    living_environment TEXT NOT NULL,
    pet_experience TEXT NOT NULL,
    readiness_notes TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Under Screening' CHECK (status IN ('Under Screening', 'Approved - Visit Barangay Hall', 'Declined')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE stray_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE animals ENABLE ROW LEVEL SECURITY;
ALTER TABLE adoption_applications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public full access stray_reports" ON stray_reports FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access animals" ON animals FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access adoption_applications" ON adoption_applications FOR ALL USING (true) WITH CHECK (true);

CREATE POLICY "Public upload and read stray-photos"
ON storage.objects FOR ALL
USING (bucket_id = 'stray-photos')
WITH CHECK (bucket_id = 'stray-photos');

